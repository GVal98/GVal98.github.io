// Системная подсказка по умолчанию. Ровно она и решает, доходит ли ответ до
// мотора: в морзянку уходят первые несколько букв, и «Париж» помещается
// целиком, а «Столица Франции — Париж» приходит как STOLI. Поэтому подсказка
// вынесена в настройки, а здесь только её начальное значение.
//
// Просьбы «коротко» модели мало: она понимает её как «коротким предложением»
// и всё равно повторяет вопрос перед ответом. Примеры показывают ровно ту
