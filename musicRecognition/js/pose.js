// Второй выключатель: нога.
//
// Слухом приложение включает себя само: заиграла музыка — значит начался вопрос.
// В зале это не всегда так. Между вопросами играет фон, ведущий говорит под
// музыку, за соседним столом свой звук — гейт то держится открытым весь раунд,
// то открывается там, где спрашивать нечего. Нога говорит прямо: подняли —
// слушай этот вопрос, опустили — молчи. Телефон при этом лежит в кармане,
// доставать его незачем, а рука свободна.
//
// Всё, что здесь есть, вышло из пяти записей акселерометра (measures/, снимала
// их motion.html) и из двух выводов, которые они сделали неизбежными.
//
// Первый: по значению позу не опознать. Разница между «нога опущена» и «нога
// поднята» — поворот телефона на 2.3°: по осям это 0.32 м/с² на самой удачной
// из них. А одна и та же поза от укладки к укладке уезжает на 8°: карман каждый
// раз принимает телефон чуть иначе, и укладка поворачивает его на 40-60°. Мало
// того, за одну семидесятисекундную серию поза уползает на 1° сама по себе —
// то есть протухла бы и калибровка, сделанная при запуске. Любой порог по
// самому значению обречён.
//
// Второй вывод добыт четвёртой и пятой записями, из другого кармана, и стоил
// первой версии этого файла жизни. Та сравнивала средний вектор тяжести до и
// после движения — и в новом кармане ступенька тяжести просела до 0.11°,
// неотличимо от дрожи: нога там крутит телефон вокруг вертикали, а поворот
// вокруг вертикали тяжесть не видит в принципе. Гироскопу же всё равно, вокруг
// чего поворот. Набег вращения за само движение — интеграл rotationRate — на
// всех 59 сменах позы из пяти записей набирает 6.0-15.6°, покой за то же окно
// даёт не больше 0.3°, а направление набега согласовано с общей осью на 0.98+
// в каждой смене и от кармана к карману почти не меняется. Двадцатикратный
// зазор против полуторакратного у тяжести — и мерка здесь одна: гироскоп.
//
// Ловим по-прежнему не позу, а ступеньку между позами: покой → короткий
// всплеск вращения → снова покой, и набег вращения за этот всплеск. Что это
// даёт:
//
//   • сноса нет вовсе — набег меряется за полсекунды самого движения, гироскопу
//     между движениями копить нечего;
//   • перекладывание телефона неважно — меряется движение, а не уровень;
//   • укладка в карман отсеивается сама: она длится 4.8-7.9 с против 0.6-0.9 с
//     у смены позы, и в maxMove не влезает;
//   • ходьба отсеивается тем же: вращение в ней не возвращается к покою,
//     тишина не наступает, ступенька не кончается.
//
// Направление берётся из калибровки — поднятия и опускания ноги, записанных
// заранее. Оно и делает гейт самоисправляющимся: это не переключатель, который
// щёлкает на каждое движение и после первого пропуска врёт наоборот, а два
// состояния, и «поднять» при уже поднятой ноге не значит ничего. На пяти
// записях: 51 смена позы из 51, направление верное во всех.
//
// Проверок на ступеньке две, и обе нужны. Первая — на весь набег: сколько
// телефон повернулся, куда бы он ни повернулся. Вторая — на то, сколько этого
// набега легло вдоль оси. Порознь ни одна не годится: по одному только набегу
// позой оказался бы любой сдвиг телефона в кармане, а по одной только
// проекции — терялись бы смены позы, у которых поворот пошёл наискось.
//
// Проверка — test/pose.test.mjs, она гоняет этот самый файл по тем же записям.

// Пороги, ниже которых начинается шум, и сверху — то, что уже не поза.
// Все взяты из measures/, каждый с запасом в разы; см. README.
export const POSE = {
  moveOn: 8,        // °/с — с этого начинается движение (покой 0.2, смена 16-40)
  moveOff: 4,       // °/с — и этим кончается, по сглаженному вращению
  smoothSec: 0.12,  // сглаживание вращения: одиночный выброс — ещё не движение
  quietSec: 0.30,   // с покоя, после которых движение считается закончившимся
  stillSec: 0.40,   // с тишины, которыми ступенька обязана быть обёрнута
  // Дольше этого — уже не смена позы, а укладка в карман. Самая ленивая
  // записанная смена (нога плюс хвост ёрзанья, слипшийся с ней) — 3.07 с,
  // самая быстрая укладка — 3.83 с; порог стоит между ними.
  maxMoveSec: 3.5,
  minAngle: 3.5,    // ° набега вращения, ниже которых движение позой не считается
  // Какая доля порога обязана лечь вдоль калиброванной оси. Не единица, потому
  // что поза меняется не в чистом виде: телефон заодно ёрзает в кармане, и
  // часть поворота уходит вбок. Требовать всё — терять такие; не требовать
  // ничего — считать позой любой поворот, куда бы он ни был.
  alongShare: 0.5,
  calSteps: 2,      // движений на калибровку: поднять ногу и опустить обратно
  learn: 0.2,       // с какой охотой ось идёт за каждой засчитанной ступенькой
  // Под вибрацией ступенька ловится по-другому, см. «набег под мотором» ниже.
  blindWin: 1.20,    // с — окно, по которому набег считается под мотором
  blindSettle: 0.35, // с — хвост того же окна: по нему видно, что поза улеглась
};

const unit = (v) => {
  const m = Math.hypot(v[0], v[1], v[2]);
  return m ? [v[0] / m, v[1] / m, v[2] / m] : null;
};
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];

/**
 * Набег вращения по кадрам [t, rx, ry, rz] — вектором, в градусах. Прямоугольник
 * по правому краю: кадры идут в 60 Гц, честнее считать не из чего.
 */
function turnOver(hist) {
  const s = [0, 0, 0];
  for (let i = 1; i < hist.length; i++) {
    const dt = hist[i][0] - hist[i - 1][0];
    s[0] += hist[i][1] * dt; s[1] += hist[i][2] * dt; s[2] += hist[i][3] * dt;
  }
  return s;
}

/**
 * Состояние ноги по гироскопу.
 *
 * Кадры отдаются в `push()`, оттуда же приходят и события: гейт сам ничего не
 * слушает и ни на что не подписан. Так его можно прогнать по записанному файлу
 * ровно тем же кодом, каким он работает на телефоне.
 */
export class PoseGate {
  constructor(opts = {}) {
    this.axis = null;       // вокруг чего поворачивается телефон при поднятии ноги
    this.minAngle = POSE.minAngle;
    this.configure(opts);
    this.up = false;        // текущее состояние ноги
    this.cal = null;        // направления, набранные калибровкой
    this.lastT = 0;
    this.blindUntil = 0;
    this.watch = null;      // сторож на время вибрации
    this.reset();
  }

  configure({ axis, minAngle } = {}) {
    if (axis !== undefined) this.axis = Array.isArray(axis) && axis.length === 3 ? unit(axis) : null;
    if (minAngle !== undefined && minAngle > 0) this.minAngle = minAngle;
  }

  /** Откалиброван ли: без оси гейт умеет только видеть движение, но не толковать его. */
  get ready() { return Boolean(this.axis); }
  get calibrating() { return this.cal !== null; }
  /** Сколько движений калибровка уже приняла: 0 — ждёт самого первого. */
  get calSteps() { return this.cal ? this.cal.length : 0; }

  /**
   * Снять ось заново: следующие движения — поднятие ноги и возврат обратно.
   * Кончается калибровка на опускании, и нога после неё опущена: ровно то
   * состояние, с которого начинается вопрос.
   */
  calibrate() {
    this.cal = [];
    this.watch = null;
    this.reset();
  }

  /**
   * Бросить калибровку на полпути. Прежняя ось, если была, остаётся в силе:
   * недоснятая — это половина оси, а половина хуже старой.
   */
  stopCalibration() {
    this.cal = null;
    this.reset();
  }

  /**
   * Ослепнуть на `sec` секунд: обычный путь под мотором не работает, см.
   * «набег под мотором». Вместо него на это время встаёт сторож.
   */
  blind(sec) {
    this.blindUntil = this.lastT + sec;
    this.reset();
    // Калибровке сторож не нужен и вреден: там движения разбирает сам человек
    // по шагам, и ступенька, пришедшая мимо шагов, сбила бы счёт.
    this.watch = this.cal ? null : { hist: [] };
  }

  /** Мотор смолк раньше, чем обещал. */
  see() {
    if (this.blindUntil > this.lastT) this.blindUntil = this.lastT;
  }

  /** Начать сначала: нога опущена, гейт закрыт. Ось и калибровка остаются. */
  arm() {
    this.up = false;
    this.watch = null;
    this.reset();
  }

  /** Забыть набранное, оставив калибровку и состояние ноги. */
  reset() {
    this.hist = [];
    this.phase = 'still';
    this.turn = [0, 0, 0];
    this.rotSm = 0;
    this.moveFrom = 0;
    this.quietFrom = 0;
    this.settleFrom = 0;
  }

  /**
   * Кадр датчика: скорость вращения по трём осям, °/с — rotationRate как есть.
   *
   * @param {number} t   время, секунды, любые монотонные часы
   * @param {number} rx  rotationRate.alpha
   * @param {number} ry  rotationRate.beta
   * @param {number} rz  rotationRate.gamma
   * @returns {?{verdict: string, angle: number, along: number, moveSec: number, age: number}}
   *   `verdict` — `up`, `down`, `calibrating`, `calibrated` или причина, по
   *   которой ступенька не в счёт: `long` — движение слишком долгое, `small` —
   *   набег не дотянул до порога, `across` — повернулось поперёк оси,
   *   `same` — нога и так в этой позе, `blind` — оси ещё нет. `age` — сколько
   *   секунд назад началось движение: от него отсчитывается начало вопроса,
   *   а решение приходит на секунду с лишним позже. Флаг `underMotor: true`
   *   при `up`/`down` значит, что ступеньку взял сторож из-под работающего
   *   мотора: мотор надо остановить, см. «набег под мотором».
   */
  push(t, rx, ry, rz) {
    const dt = this.lastT ? Math.max(0, t - this.lastT) : 0;
    this.lastT = t;
    const rot = Math.hypot(rx, ry, rz);
    // Сторож живёт на одно окно дольше самой слепоты: движение, начатое под
    // последний импульс мотора, целиком в неё не попадает, а обычному пути
    // не на чем его поймать — тишины до движения у него уже не будет.
    if (this.watch) {
      if (t >= this.blindUntil + POSE.blindWin) this.watch = null;
      else {
        const e = this.watchPush(t, rx, ry, rz);
        if (e) return e;
      }
    }
    if (t < this.blindUntil) return null;

    // Начало движения ловим по сырому вращению — оно взлетает круто, и сглаживать
    // тут значит опаздывать. Конец, наоборот, по сглаженному: в покое сырое
    // вращение изредка выбрасывает до 4 °/с, и на нём тишина не наступила бы
    // никогда.
    const k = dt > 0 ? 1 - Math.exp(-dt / POSE.smoothSec) : 1;
    this.rotSm += (rot - this.rotSm) * k;

    if (this.phase === 'still') {
      this.hist.push([t, rx, ry, rz]);
      while (this.hist.length > 1 && t - this.hist[0][0] > POSE.stillSec) this.hist.shift();
      // Тишина нужна вся: движению не с чего начинаться, пока перед ним не было
      // покоя, даже если вращение уже вовсю. Так укладка в карман и попадает
      // в гейт целиком: возня внутри неё тишины не набирает, движение не
      // кончается, зато и длительность выходит вся, и отбраковывается такое
      // одним куском, а не рассыпается на обрывки.
      if (rot > POSE.moveOn && t - this.hist[0][0] >= POSE.stillSec * 0.75) {
        // Порог замечает движение не с первого кадра, а разгон — тоже поворот.
        // Он ещё лежит в хвосте тишины, оттуда набег и начинается.
        this.turn = turnOver(this.hist);
        this.phase = 'moving';
        this.moveFrom = t;
        this.quietFrom = 0;
        this.hist = [];
      }
      return null;
    }

    // Дальше любой кадр — часть движения, пока не вынесен вердикт: набег копит
    // и хвост, где вращение уже стихло, — там его на сотые доли градуса.
    this.turn[0] += rx * dt; this.turn[1] += ry * dt; this.turn[2] += rz * dt;

    if (this.phase === 'moving') {
      if (this.rotSm > POSE.moveOff) { this.quietFrom = 0; return null; }
      if (!this.quietFrom) this.quietFrom = t;
      if (t - this.quietFrom < POSE.quietSec) return null;
      this.phase = 'settling';
      this.settleFrom = t;
      this.hist = [];
      return null;
    }

    // Пережидаем тишину после движения. Задвигались снова — тишины не вышло,
    // это всё ещё то же движение: и набег продолжает копиться, и начало
    // остаётся прежним, иначе возня из двух рывков потеряла бы своё начало.
    if (rot > POSE.moveOn) {
      this.phase = 'moving';
      this.quietFrom = 0;
      this.hist = [];
      return null;
    }
    this.hist.push([t, rx, ry, rz]);
    if (t - this.settleFrom < POSE.stillSec) return null;

    // Тишина выстояла — движение кончилось, и его набег стал ступенькой.
    // Кадры тишины остаются лежать: для следующего движения они — та самая
    // тишина перед ним.
    this.phase = 'still';
    const d = unit(this.turn);
    if (!d) return null;

    const angle = Math.hypot(this.turn[0], this.turn[1], this.turn[2]);
    const along = this.axis ? dot(this.turn, this.axis) : 0;
    const moveSec = this.quietFrom - this.moveFrom;
    const out = { angle, along, moveSec, age: t - this.moveFrom, verdict: '' };

    if (moveSec > POSE.maxMoveSec) out.verdict = 'long';
    else if (angle < this.minAngle) out.verdict = 'small';
    else if (this.cal) {
      // Первое движение калибровки — поднятие, второе — возврат. Направление
      // второго разворачиваем: обе стрелки должны смотреть в одну сторону,
      // иначе среднее из них — ноль.
      const sign = this.cal.length % 2 ? -1 : 1;
      this.cal.push(d.map((v) => v * sign));
      out.along = angle * sign;
      if (this.cal.length < POSE.calSteps) {
        out.verdict = 'calibrating';
      } else {
        this.axis = unit(this.cal.reduce((a, v) => [a[0] + v[0], a[1] + v[1], a[2] + v[2]], [0, 0, 0]));
        this.up = sign > 0;
        this.cal = null;
        out.verdict = 'calibrated';
      }
    } else if (!this.axis) out.verdict = 'blind';
    else if (Math.abs(along) < this.minAngle * POSE.alongShare) out.verdict = 'across';
    else if ((along > 0) === this.up) out.verdict = 'same';
    else {
      this.up = along > 0;
      // Ось идёт за тем, что уже засчитано. Карман принимает телефон каждый раз
      // чуть иначе, и калибровка недельной давности знает направление хуже, чем
      // последние несколько смен позы. Двигают её только засчитанные ступеньки:
      // всё, что не прошло порог, оси не касается и увести её не может.
      const step = this.up ? d : [-d[0], -d[1], -d[2]];
      this.axis = unit([
        this.axis[0] + (step[0] - this.axis[0]) * POSE.learn,
        this.axis[1] + (step[1] - this.axis[1]) * POSE.learn,
        this.axis[2] + (step[2] - this.axis[2]) * POSE.learn,
      ]);
      out.verdict = this.up ? 'up' : 'down';
      // Ступенька засчитана обычным путём — сторожу больше нечего ловить.
      // Хвост слепоты они делят, и без этого одно движение ушло бы дважды.
      this.watch = null;
    }
    return out;
  }

  /**
   * Набег под мотором.
   *
   * Пока телефон стучит ответ, обычный путь не работает: он ищет покой, всплеск
   * вращения и снова покой, а мотор держит корпус в тряске десяток секунд
   * подряд — тишина не наступает, и движению не на чем кончиться. Раньше это
   * и значило «ноги нет»: поднятие под морзянку терялось целиком.
   *
   * Здесь тот же набег вращения, только окно берётся не по тишине, а по часам.
   * Тряска мотора набегу не мешает: она болтает корпус туда-сюда, и за окно
   * это сходится почти в ноль — на записях из measures/ вибрация команды
   * оставляет за 0.8 с не больше 0.2°, тогда как самая слабая настоящая
   * ступенька — 6°.
   *
   * Пороги те же, что у обычного пути, и проверок на одну больше. Движение
   * здесь не сегментируется, а значит, не отсеивается по длительности: укладка
   * в карман и ходьба прошли бы насквозь. Вместо `maxMove` — проверка, что поза
   * улеглась: хвост окна почти не вращается. У ходьбы вращение не стихает,
   * и хвост не проходит.
   *
   * Ступенька отсюда одноразовая: сторож гаснет, отдав её. Дальше мотор
   * останавливают, слепота кончается, и дело снова ведёт обычный путь.
   */
  watchPush(t, rx, ry, rz) {
    const w = this.watch;
    w.hist.push([t, rx, ry, rz]);
    while (w.hist.length > 1 && t - w.hist[0][0] > POSE.blindWin) w.hist.shift();
    if (t - w.hist[0][0] < POSE.blindWin * 0.9) return null;
    if (!this.axis) return null;

    const turn = turnOver(w.hist);
    const angle = Math.hypot(turn[0], turn[1], turn[2]);
    if (angle < this.minAngle) return null;
    // Поза улеглась? Пока нога ещё идёт, хвост окна вращается вовсю, и набег
    // в этот момент — половина движения: решать по нему рано.
    const tail = turnOver(w.hist.filter((h) => h[0] >= t - POSE.blindSettle));
    if (Math.hypot(tail[0], tail[1], tail[2]) >= this.minAngle * POSE.alongShare) return null;

    const along = dot(turn, this.axis);
    if (Math.abs(along) < this.minAngle * POSE.alongShare) return null;
    if ((along > 0) === this.up) return null;

    this.up = along > 0;
    this.watch = null;
    this.reset();
    // Ось сторож не двигает: набег из-под мотора знает направление хуже
    // чистого, и учить по нему то, чем потом будут мерить, не за что.
    //
    // `age` — ноль, и это не отговорка. Всё время, что мотор стучал, микрофон
    // был глух, и музыки за эту секунду не записано: отматывать вопрос назад
    // некуда, там нет ничего, кроме собственного ответа.
    return { verdict: this.up ? 'up' : 'down', angle, along, moveSec: 0, age: 0, underMotor: true };
  }
}

/**
 * Подписка на датчик. Вынесена сюда же, потому что деваться ей больше некуда:
 * гейт без кадров бесполезен, а кадры добываются одинаково всегда.
 */
export class PoseSensor {
  constructor(onSample) {
    this.onSample = onSample;
    this.started = false;
    this.frames = 0;
    this.hasRotation = false;
    this.onMotion = this.onMotion.bind(this);
  }

  static get needsPermission() {
    return typeof DeviceMotionEvent !== 'undefined'
      && typeof DeviceMotionEvent.requestPermission === 'function';
  }

  /** @returns {Promise<boolean>} разрешили ли. Спрашивать можно только из жеста. */
  static async ask() {
    if (!PoseSensor.needsPermission) return true;
    return await DeviceMotionEvent.requestPermission() === 'granted';
  }

  start() {
    if (this.started) return;
    this.started = true;
    window.addEventListener('devicemotion', this.onMotion);
  }

  stop() {
    this.started = false;
    window.removeEventListener('devicemotion', this.onMotion);
  }

  onMotion(e) {
    const r = e.rotationRate;
    // Гироскоп — это весь гейт. Браузер может отдавать событие и без него,
    // и это не «нет датчика», а «датчик есть, но не тот»; знать об этом
    // должен вызывающий — по hasRotation.
    const has = r && (r.alpha != null || r.beta != null || r.gamma != null);
    if (has) this.hasRotation = true;
    this.frames++;
    this.onSample(performance.now() / 1000,
      has ? r.alpha || 0 : 0, has ? r.beta || 0 : 0, has ? r.gamma || 0 : 0);
  }
}
