// Второй выключатель: нога.
//
// Слухом приложение включает себя само: заиграла музыка — значит начался вопрос.
// В зале это не всегда так. Между вопросами играет фон, ведущий говорит под
// музыку, за соседним столом свой звук — гейт то держится открытым весь раунд,
// то открывается там, где спрашивать нечего. Нога говорит прямо: подняли —
// слушай этот вопрос, опустили — молчи. Телефон при этом лежит в кармане,
// доставать его незачем, а рука свободна.
//
// Всё, что здесь есть, вышло из трёх записей акселерометра (measures/, снимала
// их motion.html) и из одного вывода, который они сделали неизбежным.
//
// По значению позу не опознать. Разница между «нога опущена» и «нога поднята» —
// поворот телефона на 2.3°: по осям это 0.32 м/с² на самой удачной из них.
// А одна и та же поза от укладки к укладке уезжает на 8°: карман каждый раз
// принимает телефон чуть иначе, и укладка поворачивает его на 40-60°. Мало
// того, за одну семидесятисекундную серию поза уползает на 1° сама по себе —
// то есть протухла бы и калибровка, сделанная при запуске. Любой порог по
// самому значению обречён, и калибровка «вот это выключено» его не спасает.
//
// Зато сам момент смены видно превосходно, и видно по двум приметам сразу.
// Вращение: в покое 0.2 °/с, на смене позы всплеск 16-31 °/с — разница в сто
// раз. И поворот вектора тяжести между двумя соседними полками: в покое 0.06°
// (худшая за все три записи — 0.63°), на смене позы 1.2-3.8°.
//
// Отсюда весь гейт: ловим не позу, а ступеньку между позами. Покой → короткий
// всплеск вращения → снова покой, и сравниваем средний вектор тяжести до и
// после. Что это даёт:
//
//   • сноса нет вовсе — сравниваются две полки в полусекунде друг от друга,
//     между ними уползать нечему;
//   • перекладывание телефона неважно — сравнивается разность, а не уровень;
//   • укладка в карман отсеивается сама: она длится 4.8-7.9 с против 0.6-0.9 с
//     у смены позы, и в maxMove не влезает;
//   • ходьба отсеивается тем же: вращение в ней не возвращается к покою,
//     полка не набирается, сравнивать нечего.
//
// Направление берётся из калибровки — поднятия и опускания ноги, записанных
// заранее. Оно и делает гейт самоисправляющимся: это не переключатель, который
// щёлкает на каждое движение и после первого пропуска врёт наоборот, а два
// состояния, и «поднять» при уже поднятой ноге не значит ничего. На тех же
// трёх записях: 21 смена позы из 21, направление верное во всех 21.
//
// Проверок на ступеньке две, и обе нужны. Первая — на весь поворот: сколько
// телефон повернулся, куда бы он ни повернулся. Вторая — на то, сколько этого
// поворота легло вдоль оси. Порознь ни одна не годится: по одному только
// повороту позой оказался бы любой сдвиг телефона в кармане, а по одной только
// проекции — терялись бы настоящие смены позы, у которых поворот пошёл
// наискось. Такая среди 21 записанной ровно одна: поза сменилась вместе со
// сдвигом, и вдоль оси легло 0.88° из 2.24°.
//
// Она же объясняет, почему калибровка берёт два движения, а не одно, и почему
// ось потом уточняется на каждом засчитанном. Ось с одного поднятия оставляет
// этой ступеньке 0.51° — ровно на границе; два движения дают 0.73°,
// согласованная по всем 21 — 0.88°. Уточнение приводит ось к согласованной за
// первые же несколько смен, так что и калибровка недельной давности чинит себя
// сама. Двигают ось только засчитанные ступеньки: всё, что не прошло пороги,
// её не касается.
//
// Проверка — test/pose.test.mjs, она гоняет этот самый файл по тем же записям.

const DEG = 180 / Math.PI;

// Пороги, ниже которых начинается шум, и сверху — то, что уже не поза.
// Все взяты из measures/, каждый с запасом в разы; см. README.
export const POSE = {
  moveOn: 8,        // °/с — с этого начинается движение (покой 0.2, смена 16-31)
  moveOff: 4,       // °/с — и этим кончается, по сглаженному вращению
  smoothSec: 0.12,  // сглаживание вращения: одиночный выброс — ещё не движение
  quietSec: 0.30,   // с покоя, после которых движение считается законченным
  plateauSec: 0.40, // с, по которым берётся средняя поза до и после
  maxMoveSec: 2.5,  // с — дольше это уже не смена позы, а ходьба или карман
  minAngle: 1.0,    // ° поворота, ниже которых движение позой не считается
  // Какая доля порога обязана лечь вдоль калиброванной оси. Не единица, потому
  // что поза меняется не в чистом виде: на одной из 21 записанной ступеньки
  // телефон заодно сдвинулся в кармане, и вдоль оси легло 0.88° из 2.24°.
  // Требовать всё — терять такие; не требовать ничего — считать позой любой
  // поворот, куда бы он ни был.
  alongShare: 0.5,
  calSteps: 2,      // движений на калибровку: поднять ногу и опустить обратно
  learn: 0.2,       // с какой охотой ось идёт за каждой засчитанной ступенькой
  // Под вибрацией ступенька ловится по-другому, см. «полка под мотором» ниже.
  blindWin: 1.00,    // с — окно, по которому берётся средняя поза под мотором
  blindSettle: 0.35, // с — хвост того же окна: по нему видно, что поза улеглась
};

const unit = (v) => {
  const m = Math.hypot(v[0], v[1], v[2]);
  return m ? [v[0] / m, v[1] / m, v[2] / m] : null;
};
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];

/**
 * Угол между двумя позами, градусы. Хорда против угла: на градусах, о которых
 * здесь речь, разница лежит в пятом знаке, но считать угол честно ничего
 * не стоит.
 */
const between = (a, b) => 2 * Math.asin(
  Math.min(1, Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]) / 2),
) * DEG;

/** Средняя поза по набранным кадрам — единичным вектором. */
function meanUnit(hist) {
  const s = [0, 0, 0];
  for (const h of hist) { s[0] += h[1]; s[1] += h[2]; s[2] += h[3]; }
  return unit(s);
}

/**
 * Состояние ноги по акселерометру.
 *
 * Кадры отдаются в `push()`, оттуда же приходят и события: гейт сам ничего не
 * слушает и ни на что не подписан. Так его можно прогнать по записанному файлу
 * ровно тем же кодом, каким он работает на телефоне.
 */
export class PoseGate {
  constructor(opts = {}) {
    this.axis = null;       // куда поворачивается телефон, когда нога поднимается
    this.minAngle = POSE.minAngle;
    this.configure(opts);
    this.up = false;        // текущее состояние ноги
    this.cal = null;        // направления, набранные калибровкой
    this.lastT = 0;
    this.blindUntil = 0;
    this.watch = null;      // сторож на время вибрации
    this.reset();
  }

  configure({ axis, minAngle } = {}) {
    if (axis !== undefined) this.axis = Array.isArray(axis) && axis.length === 3 ? unit(axis) : null;
    if (minAngle !== undefined && minAngle > 0) this.minAngle = minAngle;
  }

  /** Откалиброван ли: без оси гейт умеет только видеть движение, но не толковать его. */
  get ready() { return Boolean(this.axis); }
  get calibrating() { return this.cal !== null; }
  /** Сколько движений калибровка уже приняла: 0 — ждёт самого первого. */
  get calSteps() { return this.cal ? this.cal.length : 0; }

  /**
   * Снять ось заново: следующие движения — поднятие ноги и возврат обратно.
   * Кончается калибровка на опускании, и нога после неё опущена: ровно то
   * состояние, с которого начинается вопрос.
   */
  calibrate() {
    this.cal = [];
    this.watch = null;
    this.reset();
  }

  /**
   * Бросить калибровку на полпути. Прежняя ось, если была, остаётся в силе:
   * недоснятая — это половина оси, а половина хуже старой.
   */
  stopCalibration() {
    this.cal = null;
    this.reset();
  }

  /**
   * Ослепнуть на `sec` секунд: обычный путь под мотором не работает, см.
   * «полка под мотором». Вместо него на это время встаёт сторож, и опорой ему
   * служит последняя чистая полка — та, что набралась до тряски. Её и снимаем,
   * пока `reset()` не выбросил кадры.
   */
  blind(sec) {
    const pre = this.hist.length > 1 && this.lastT - this.hist[0][0] >= POSE.plateauSec * 0.75
      ? meanUnit(this.hist)
      : null;
    this.blindUntil = this.lastT + sec;
    this.reset();
    // Калибровке сторож не нужен и вреден: там движения разбирает сам человек
    // по шагам, и ступенька, пришедшая мимо шагов, сбила бы счёт.
    this.watch = this.cal ? null : { pre, hist: [] };
  }

  /** Мотор смолк раньше, чем обещал. */
  see() {
    if (this.blindUntil > this.lastT) this.blindUntil = this.lastT;
  }

  /** Начать сначала: нога опущена, гейт закрыт. Ось и калибровка остаются. */
  arm() {
    this.up = false;
    this.watch = null;
    this.reset();
  }

  /** Забыть набранное, оставив калибровку и состояние ноги. */
  reset() {
    this.hist = [];
    this.phase = 'still';
    this.pre = null;
    this.rotSm = 0;
    this.moveFrom = 0;
    this.quietFrom = 0;
  }

  /**
   * Кадр датчика.
   *
   * @param {number} t   время, секунды, любые монотонные часы
   * @param {number} gx  ускорение с тяжестью, м/с²
   * @param {number} gy
   * @param {number} gz
   * @param {number} rot скорость вращения, °/с, по модулю
   * @returns {?{verdict: string, angle: number, along: number, moveSec: number, age: number}}
   *   `verdict` — `up`, `down`, `calibrating`, `calibrated` или причина, по
   *   которой ступенька не в счёт: `long` — движение слишком долгое, `small` —
   *   поворот не дотянул до порога, `across` — повернулось поперёк оси,
   *   `same` — нога и так в этой позе, `blind` — оси ещё нет. `age` — сколько
   *   секунд назад началось движение: от него отсчитывается начало вопроса,
   *   а решение приходит почти на полторы секунды позже. Флаг
   *   `underMotor: true` при `up`/`down` значит, что ступеньку взял сторож
   *   из-под работающего мотора: мотор надо остановить, см. «полка под мотором».
   */
  push(t, gx, gy, gz, rot) {
    const dt = this.lastT ? Math.max(0, t - this.lastT) : 0;
    this.lastT = t;
    // Сторож живёт на одно окно дольше самой слепоты: движение, начатое под
    // последний импульс мотора, целиком в неё не попадает, а обычному пути
    // не на чем его поймать — полки до движения у него уже не будет.
    if (this.watch) {
      if (t >= this.blindUntil + POSE.blindWin) this.watch = null;
      else {
        const e = this.watchPush(t, gx, gy, gz);
        if (e) return e;
      }
    }
    if (t < this.blindUntil) return null;

    // Начало движения ловим по сырому вращению — оно взлетает круто, и сглаживать
    // тут значит опаздывать. Конец, наоборот, по сглаженному: в покое сырое
    // вращение изредка выбрасывает до 4 °/с, и на нём тишина не наступила бы
    // никогда.
    const k = dt > 0 ? 1 - Math.exp(-dt / POSE.smoothSec) : 1;
    this.rotSm += (rot - this.rotSm) * k;

    if (this.phase === 'still') {
      this.hist.push([t, gx, gy, gz]);
      while (this.hist.length > 1 && t - this.hist[0][0] > POSE.plateauSec) this.hist.shift();
      // Полка нужна вся: по двум кадрам среднее — это те же два кадра. Пока она
      // не набралась, движение не начинается, даже если вращение уже вовсю.
      // Так укладка в карман и попадает в гейт целиком: полка внутри неё
      // набирается из самого движения, зато и длительность выходит вся, и
      // отбраковывается такое одним куском, а не рассыпается на обрывки.
      if (rot > POSE.moveOn && t - this.hist[0][0] >= POSE.plateauSec * 0.75) {
        this.pre = meanUnit(this.hist);
        this.phase = 'moving';
        this.moveFrom = t;
        this.quietFrom = 0;
        this.hist = [];
      }
      return null;
    }

    if (this.phase === 'moving') {
      if (this.rotSm > POSE.moveOff) { this.quietFrom = 0; return null; }
      if (!this.quietFrom) this.quietFrom = t;
      if (t - this.quietFrom < POSE.quietSec) return null;
      this.phase = 'settling';
      this.hist = [];
      return null;
    }

    // Набираем полку после движения. Задвигались снова — полки не вышло,
    // ждём следующей тишины; начало движения при этом остаётся прежним, иначе
    // возня из двух рывков потеряла бы своё начало.
    if (rot > POSE.moveOn) {
      this.phase = 'moving';
      this.quietFrom = 0;
      this.hist = [];
      return null;
    }
    this.hist.push([t, gx, gy, gz]);
    if (t - this.hist[0][0] < POSE.plateauSec) return null;

    const post = meanUnit(this.hist);
    this.phase = 'still';
    if (!post || !this.pre) return null;

    const d = [post[0] - this.pre[0], post[1] - this.pre[1], post[2] - this.pre[2]];
    const angle = between(post, this.pre);
    const along = this.axis ? dot(d, this.axis) * DEG : 0;
    const moveSec = this.quietFrom - this.moveFrom;
    const out = { angle, along, moveSec, age: t - this.moveFrom, verdict: '' };

    if (moveSec > POSE.maxMoveSec) out.verdict = 'long';
    else if (angle < this.minAngle) out.verdict = 'small';
    else if (this.cal) {
      // Первое движение калибровки — поднятие, второе — возврат. Направление
      // второго разворачиваем: обе стрелки должны смотреть в одну сторону,
      // иначе среднее из них — ноль.
      const sign = this.cal.length % 2 ? -1 : 1;
      this.cal.push(unit(d).map((v) => v * sign));
      out.along = angle * sign;
      if (this.cal.length < POSE.calSteps) {
        out.verdict = 'calibrating';
      } else {
        this.axis = unit(this.cal.reduce((a, v) => [a[0] + v[0], a[1] + v[1], a[2] + v[2]], [0, 0, 0]));
        this.up = sign > 0;
        this.cal = null;
        out.verdict = 'calibrated';
      }
    } else if (!this.axis) out.verdict = 'blind';
    else if (Math.abs(along) < this.minAngle * POSE.alongShare) out.verdict = 'across';
    else if ((along > 0) === this.up) out.verdict = 'same';
    else {
      this.up = along > 0;
      // Ось идёт за тем, что уже засчитано. Карман принимает телефон каждый раз
      // чуть иначе, и калибровка недельной давности знает направление хуже, чем
      // последние несколько смен позы. Двигают её только засчитанные ступеньки:
      // всё, что не прошло порог, оси не касается и увести её не может.
      const step = unit(this.up ? d : [-d[0], -d[1], -d[2]]);
      if (step) {
        this.axis = unit([
          this.axis[0] + (step[0] - this.axis[0]) * POSE.learn,
          this.axis[1] + (step[1] - this.axis[1]) * POSE.learn,
          this.axis[2] + (step[2] - this.axis[2]) * POSE.learn,
        ]);
      }
      out.verdict = this.up ? 'up' : 'down';
      // Ступенька засчитана обычным путём — сторожу больше нечего ловить.
      // Хвост слепоты они делят, и без этого одно движение ушло бы дважды.
      this.watch = null;
    }
    return out;
  }

  /**
   * Полка под мотором.
   *
   * Пока телефон стучит ответ, обычный путь не работает: он ищет покой, всплеск
   * вращения и снова покой, а мотор держит корпус в тряске десяток секунд
   * подряд — покой не наступает, и сравнивать нечего. Раньше это и значило
   * «ноги нет»: поднятие под морзянку терялось целиком.
   *
   * Здесь то же сравнение полок, только полка берётся не по вращению, а по
   * часам, и опорная — та, что набралась до вибрации. Тряска среднему вектору
   * тяжести не мешает: на записях из measures/ за полсекунды мотора среднее
   * уезжает на 0.41° при окне 0.5 с и на 0.69° при окне 0.3 с, тогда как самая
   * слабая настоящая ступенька — 1.11°. Отсюда и окно: чем оно длиннее, тем
   * тише мотор в среднем, а ждать дольше секунды незачем — обычный путь и сам
   * отвечает через 1.3-1.6 с.
   *
   * Пороги те же, что у обычного пути, и проверок на одну больше. Движение
   * здесь не сегментируется, а значит, не отсеивается по длительности: укладка
   * в карман и ходьба прошли бы насквозь. Вместо `maxMove` — проверка, что поза
   * улеглась: хвост окна должен сойтись со всем окном. У ходьбы среднее едет,
   * и не сходится.
   *
   * Ступенька отсюда одноразовая: сторож гаснет, отдав её. Дальше мотор
   * останавливают, слепота кончается, и дело снова ведёт обычный путь.
   */
  watchPush(t, gx, gy, gz) {
    const w = this.watch;
    w.hist.push([t, gx, gy, gz]);
    while (w.hist.length > 1 && t - w.hist[0][0] > POSE.blindWin) w.hist.shift();
    if (t - w.hist[0][0] < POSE.blindWin * 0.9) return null;

    const cur = meanUnit(w.hist);
    if (!cur) return null;
    // Полки до вибрации не было — гейт только что включили или сбросили.
    // Тогда опорой становится первое окно под мотором: оно шумнее чистого
    // на те самые доли градуса, но это лучше, чем не ловить ничего.
    if (!w.pre) { w.pre = cur; return null; }
    if (!this.axis) return null;

    const tail = meanUnit(w.hist.filter((h) => h[0] >= t - POSE.blindSettle));
    if (!tail || between(tail, cur) >= this.minAngle * POSE.alongShare) return null;

    const d = [cur[0] - w.pre[0], cur[1] - w.pre[1], cur[2] - w.pre[2]];
    const angle = between(cur, w.pre);
    const along = dot(d, this.axis) * DEG;
    if (angle < this.minAngle) return null;
    if (Math.abs(along) < this.minAngle * POSE.alongShare) return null;
    if ((along > 0) === this.up) return null;

    this.up = along > 0;
    this.watch = null;
    this.reset();
    // Ось сторож не двигает: полка под мотором знает направление хуже чистой,
    // и учить по ней то, чем потом будут мерить, не за что.
    //
    // `age` — ноль, и это не отговорка. Всё время, что мотор стучал, микрофон
    // был глух, и музыки за эту секунду не записано: отматывать вопрос назад
    // некуда, там нет ничего, кроме собственного ответа.
    return { verdict: this.up ? 'up' : 'down', angle, along, moveSec: 0, age: 0, underMotor: true };
  }
}

/**
 * Подписка на датчик. Вынесена сюда же, потому что деваться ей больше некуда:
 * гейт без кадров бесполезен, а кадры добываются одинаково всегда.
 */
export class PoseSensor {
  constructor(onSample) {
    this.onSample = onSample;
    this.started = false;
    this.frames = 0;
    this.hasRotation = false;
    this.onMotion = this.onMotion.bind(this);
  }

  static get needsPermission() {
    return typeof DeviceMotionEvent !== 'undefined'
      && typeof DeviceMotionEvent.requestPermission === 'function';
  }

  /** @returns {Promise<boolean>} разрешили ли. Спрашивать можно только из жеста. */
  static async ask() {
    if (!PoseSensor.needsPermission) return true;
    return await DeviceMotionEvent.requestPermission() === 'granted';
  }

  start() {
    if (this.started) return;
    this.started = true;
    window.addEventListener('devicemotion', this.onMotion);
  }

  stop() {
    this.started = false;
    window.removeEventListener('devicemotion', this.onMotion);
  }

  onMotion(e) {
    const g = e.accelerationIncludingGravity;
    if (!g || g.x == null) return;
    const r = e.rotationRate;
    // Вращение — половина всего гейта: без него движение от покоя не отличить.
    // Браузер может отдавать событие и без него, и это не «нет датчика», а
    // «датчик есть, но не тот»; знать об этом должен вызывающий.
    const rot = r && (r.alpha != null || r.beta != null || r.gamma != null)
      ? Math.hypot(r.alpha || 0, r.beta || 0, r.gamma || 0)
      : null;
    if (rot !== null) this.hasRotation = true;
    this.frames++;
    this.onSample(performance.now() / 1000, g.x || 0, g.y || 0, g.z || 0, rot ?? 0);
  }
}
