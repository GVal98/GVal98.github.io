// не надо. Третий пример про другое: у модели нет ни фото, ни экрана, и
// объяснять это она будет длиннее, чем что угодно ещё. «Не знаю» — тоже
// ответ, и стучать его надо быстрее любого извинения.
//
// Про последний вопрос — потому что границы клипа проводит нога, а не тишина
// в зале. Поднялась она чуть раньше — и в запись попадает хвост предыдущего
// вопроса, ведущий повторяет его же другими словами, за соседним столом
// спрашивают своё. Модели без указания всё равно, на какой из них отвечать,
