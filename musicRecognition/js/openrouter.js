// Модель взята из тех, что принимают звук напрямую. Расшифровывать вопрос
// в текст отдельным запросом значит платить дважды и терять на расшифровке
// то, чего в ней не остаётся: кто спрашивал, с какой интонацией, что было
// сказано неразборчиво. Модель слышит запись сама.
