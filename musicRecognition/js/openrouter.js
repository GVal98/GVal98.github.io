// Ошибки, у которых есть свой текст. Остальные показываем как пришли: список
// кодов у OpenRouter открытый, и подставлять вместо незнакомого «что-то пошло
// не так» значит прятать единственное, что о нём известно.
const ERRORS = {
  400: 'OpenRouter no ha aceptado la solicitud',
  401: 'Clave de API de OpenRouter no válida',
  402: 'No quedan créditos en la cuenta de OpenRouter',
  403: 'El fragmento no ha pasado la moderación',
  408: 'El modelo ha tardado demasiado en responder',
  413: 'El fragmento es demasiado grande',
  429: 'Se ha agotado el límite de solicitudes',
  502: 'El modelo no ha respondido',
  503: 'Ahora mismo no hay capacidad para este modelo',
};

// Само не рассосётся: неверный ключ верным не станет, а кредиты на счёте не
// появятся. Повторять такое — выбрасывать клипы в пустоту до конца раунда.
const FATAL = new Set([401, 402]);

export class AskError extends Error {
  constructor(code, message, fatal = false) {
    super(message);
    this.code = code;
    this.fatal = fatal;
  }
}

/**
 * @param {Blob} blob    WAV-клип
 * @param {string} token API-ключ OpenRouter
 * @param {object} opts
 * @returns {Promise<string>} ответ модели; пустая строка — сказать было нечего
 */
export async function ask(blob, token, { signal, model = MODEL, system } = {}) {
  if (!token) throw new AskError(401, 'No se ha indicado la clave de API de OpenRouter', true);

  const data = await base64(blob);
  const res = await fetch(ENDPOINT, {
    method: 'POST',
    signal,
    headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model,
      messages: [
        { role: 'system', content: system || SYSTEM },
        // Звук идёт отдельной частью сообщения и без текста рядом: что с ним
        // делать, уже сказано системной подсказкой, а повторять это же
        // словами в самом вопросе значит спорить с ней за внимание модели.
        { role: 'user', content: [{ type: 'input_audio', input_audio: { data, format: 'wav' } }] },
      ],
    }),
  });

  // Ошибка приходит двумя путями: кодом HTTP и полем `error` внутри ответа
  // с кодом 200. Второй путь — это когда запрос до провайдера дошёл, а тот
  // отказал; пропустить его значит принять отказ за пустой ответ.
  const body = await res.json().catch(() => null);
  const fault = body?.error;
  if (!res.ok || fault) {
    const code = Number(fault?.code) || res.status;
    throw new AskError(code, ERRORS[code] || fault?.message || `HTTP ${res.status} de openrouter.ai`, FATAL.has(code));
  }
  return text(body);
}

/**
 * Ответ модели одной строкой. `content` бывает и массивом кусков — так его
 * отдаёт часть провайдеров, — а бывает и пустым: модель уткнулась в лимит
 * токенов или отказалась отвечать. Пустая строка здесь не ошибка, а ответ
 * «сказать нечего», и разбирается она выше.
 */
function text(body) {
  const content = body?.choices?.[0]?.message?.content;
  const raw = Array.isArray(content)
    ? content.map((part) => (typeof part === 'string' ? part : part?.text || '')).join('')
    : content;
  return String(raw ?? '').trim();
}

/**
 * Клип в base64: ссылку на звук эндпоинт не принимает, только сами байты.
 * Через FileReader, а не циклом по байтам: клип весит до трёх мегабайт,
 * и `String.fromCharCode(...bytes)` на нём переполняет стек аргументов.
 */
function base64(blob) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => {
      const url = String(reader.result);
      resolve(url.slice(url.indexOf(',') + 1));
    };
    reader.onerror = () => reject(reader.error || new Error('No se ha podido leer el fragmento'));
    reader.readAsDataURL(blob);
  });
}
